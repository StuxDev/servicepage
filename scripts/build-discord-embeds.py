#!/usr/bin/env python3
"""Write each page's Discord link preview (a component embed) into its <head>.

Run from anywhere: python scripts/build-discord-embeds.py
              or:  python scripts/build-discord-embeds.py --check   (exit 1 if a page is out of date)

Discord reads <script id="discord:component-embed" type="application/json"> from a page's <head>
and shows it instead of the plain preview; the page's <title> and description stay as the
fallback. This is a static site, so the JSON is pre-built here and committed in each page.
Page text goes through discord_md() so names and descriptions show as plain text, and a payload
over Discord's 3,000-byte limit is left out (an HTML comment instead). The 404 page gets none.
Re-run it after changing a page's <title> or description (build-sitemap.py runs it for you).

Copyright (c) Stux.Group. All Rights Reserved. Stux.Dev is operated by Stux Group Ltd.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE_URL = "https://" + (ROOT / "CNAME").read_text(encoding="utf-8").strip()
SITE_NAME = "Stux.Dev Service Page"
ACCENT = "#FD6602"  # the Stux.Dev brand colour
ICON_URL = "https://global.media.stux.dev/icon.png"
MAX_BYTES = 3000  # Discord's limit for the whole payload

# (source file, path, kind). 404.html is left out on purpose: error pages get no embed.
PAGES = [
    ("index.html", "/", "home"),
    ("changelog.html", "/changelog", "changelog"),
    ("legal.html", "/legal", "legal"),
    ("legal/privacy.html", "/legal/privacy", "page"),
    ("legal/terms.html", "/legal/terms", "page"),
    ("legal/cookies.html", "/legal/cookies", "page"),
    ("legal/imprint.html", "/legal/imprint", "page"),
    ("legal/disclaimer.html", "/legal/disclaimer", "page"),
    ("legal/opt-out.html", "/legal/opt-out", "page"),
    ("sitemap/index.html", "/sitemap/", "page"),
]
LEGAL_PAGES = [("Privacy Policy", "privacy"), ("Terms and Ethics", "terms"), ("Cookies Policy", "cookies"),
               ("Imprint", "imprint"), ("Disclaimer", "disclaimer"), ("Opt-Out Preferences", "opt-out")]

COMMENT = ("    <!-- Discord link preview, generated by scripts/build-discord-embeds.py"
           " (the title and description are its fallback) -->\n")
BLOCK = re.compile(r'    <!-- Discord link preview.*?-->\n    (?:<script id="discord:component-embed"[^\n]*?</script>'
                   r'|<!-- discord:component-embed left out[^\n]*?-->)\n')
DESCRIPTION = re.compile(r'^ *<meta name="description" content="[^"]*">\n', re.M)


def discord_md(s: str) -> str:
    """Escapes Discord markdown: inline formatting, link brackets and backslashes anywhere;
    headings, quotes and list markers only at a line start."""
    s = re.sub(r"([\\*_~`|\[\]])", r"\\\1", s)
    return re.sub(r"^([#>-])", r"\\\1", s, flags=re.M)


def text(markdown: str) -> dict:
    return {"type": 10, "content": markdown}


def buttons(links: list) -> dict:
    """A row of link buttons from (label, absolute URL) pairs."""
    return {"type": 1, "components": [{"type": 2, "style": 5, "label": label[:80], "url": url} for label, url in links]}


def section(markdown: str) -> dict:
    """Text with the Stux.Dev icon beside it."""
    return {"type": 9, "components": [text(markdown)], "accessory": {"type": 11, "media": {"url": ICON_URL}}}


def url(path: str) -> str:
    return BASE_URL + path


def site_label() -> str:
    """The small site-name line above a page's title (Discord subtext), like a normal preview's."""
    return "-# [" + discord_md(SITE_NAME) + "](" + url("/") + ")\n"


def payload(components: list):
    """The JSON for the <script>, or None when it's over Discord's limit."""
    data = {"component": {"type": 17, "accent_color": int(ACCENT.lstrip("#"), 16), "components": components}}
    out = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    out = out.replace("</", "<\\/")  # can't close the <script> early
    return None if len(out.encode("utf-8")) > MAX_BYTES else out


def embed(components: list) -> str:
    out = payload(components)
    if out is None:
        return f"<!-- discord:component-embed left out: over {MAX_BYTES} bytes -->"
    return '<script id="discord:component-embed" type="application/json">' + out + "</script>"


def home_embed() -> str:
    return embed([
        section("# [" + discord_md(SITE_NAME) + "](" + url("/") + ")\n**This service hasn't been set up yet.**\n"
                + discord_md("Whoever runs this service hasn't set it up yet. Check back soon, or get in touch at hello@stux.dev if that's you.")),
        buttons([("Stux.Dev", "https://stux.dev"), ("All services", "https://services.stux.dev")]),
    ])


def changelog_embed(title: str, desc: str, page_url: str) -> str:
    return embed([
        section(site_label() + "## [" + discord_md(title) + "](" + page_url + ")\n" + discord_md(desc)
                + "\n-# Versioned by release date (Date Versioning, YY.MM.DD)"),
        buttons([("Open changelog", page_url), ("Date Versioning", "https://datevers.ing")]),
    ])


def legal_embed(title: str, desc: str, page_url: str) -> str:
    links = ["[" + discord_md(name) + "](" + url("/legal/" + slug) + ")" for name, slug in LEGAL_PAGES]
    return embed([
        section(site_label() + "## [" + discord_md(title) + "](" + page_url + ")\n" + discord_md(desc)),
        text(" · ".join(links)),
        buttons([("Open", page_url), ("Home", url("/"))]),
    ])


def page_embed(title: str, desc: str, page_url: str) -> str:
    return embed([
        section(site_label() + "## [" + discord_md(title) + "](" + page_url + ")\n" + discord_md(desc)),
        buttons([("Open", page_url), ("Home", url("/"))]),
    ])


def head_meta(page: str) -> tuple:
    """The page's title (without the " — Stux.Group" / " | Legal" suffixes) and description."""
    title = html.unescape(re.search(r"<title>(.*?)</title>", page, re.S).group(1).strip())
    title = re.sub(r" (—|-|\|) .*$", "", title)
    desc = html.unescape(re.search(r'<meta name="description" content="([^"]*)">', page).group(1))
    return title, desc


def build(page: str, path: str, kind: str) -> str:
    """The page with its Discord block replaced (or added after the description meta)."""
    page = BLOCK.sub("", page)
    title, desc = head_meta(page)
    if kind == "home":
        block = home_embed()
    elif kind == "changelog":
        block = changelog_embed(title, desc, url(path))
    elif kind == "legal":
        block = legal_embed("Boring Legal Stuff", desc, url(path))
    else:
        block = page_embed(title, desc, url(path))
    m = DESCRIPTION.search(page)
    return page[:m.end()] + COMMENT + "    " + block + "\n" + page[m.end():]


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for src, path, kind in PAGES:
        file = ROOT / src
        page = file.read_text(encoding="utf-8")
        new = build(page, path, kind)
        if new != page:
            stale.append(src)
            if not check:
                file.write_text(new, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Out of date (run python scripts/build-discord-embeds.py): " + ", ".join(stale))
            return 1
        print(f"Discord embeds up to date ({len(PAGES)} pages)")
        return 0
    print(f"Wrote Discord embeds for {len(stale)} of {len(PAGES)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
